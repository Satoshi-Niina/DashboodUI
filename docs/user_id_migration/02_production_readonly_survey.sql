-- ============================================================================
-- 本番専用・読み取り専用 突合調査SQL（common_user_id 移行）
-- 実行方式: SELECT のみ。UPDATE/INSERT/DDLは一切含まない。
-- 目的: ローカルの件数・対応表を流用せず、本番だけの区分別件数と
--       対応表の元データを作成する。
-- 前提: common_db と各テナントDBは別データベースであり、DB間クロスクエリは
--       できないため、まず 1) を common_db で、2) を各テナントDBで実行し、
--       結果ファイル（CSV等）を運用者側で突き合わせる。
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) common_db で実行: 突合の基準となる正本ユーザー一覧を取得
-- ----------------------------------------------------------------------------
SELECT
  id            AS common_user_id,
  username,
  is_active,
  created_at     -- 列が存在しない場合はコメントアウトすること（要事前確認）
FROM public.users
ORDER BY username, id;

-- ----------------------------------------------------------------------------
-- 2) 各テナントDBで実行: テナント側ユーザー一覧を取得
--    ※ このSELECTを対象テナントDBの数だけ実行し、DB名ごとにファイルを分ける。
-- ----------------------------------------------------------------------------
SELECT
  current_database() AS tenant_db,
  id                  AS tenant_user_id,
  username,
  role,
  is_active
FROM public.users
ORDER BY username, id;

-- ----------------------------------------------------------------------------
-- 3) 運用者側での突合手順（DBでは実行できないため手順として明記）
--    1) と 2) の結果を username で外部結合し、次の区分に分類する。
--    - id完全一致                                → 区分A候補
--    - username一致・id不一致・双方1対1           → 区分B候補（要承認）
--    - 同一usernameが複数DB/複数idに対応           → 区分C（対象外・要人手確認）
--    - どちらか一方にしか存在しない                → 区分D（対象外）
--    この結果件数を「本番の期待件数」として別途記録する。
--    ローカル調査で得た件数（区分A=1件、区分B=3件等）は一切参照しない。
-- ----------------------------------------------------------------------------

-- ----------------------------------------------------------------------------
-- 4) 参考: テナントDB側で、同一usernameが複数idで重複していないかの事前検知
--    （区分Cの機械的な一次スクリーニングに使う。書き込みは行わない）
-- ----------------------------------------------------------------------------
SELECT
  current_database() AS tenant_db,
  username,
  COUNT(*)            AS row_count,
  array_agg(id ORDER BY id) AS ids
FROM public.users
GROUP BY username
HAVING COUNT(*) > 1;

-- ----------------------------------------------------------------------------
-- 5) 参考: テナントDBの users 件数・稼働状況の概況（移行要否判断の材料。
--    0件のテナントは移行対象データが無いことの確認に使う）
-- ----------------------------------------------------------------------------
SELECT
  current_database()                    AS tenant_db,
  COUNT(*)                              AS total_users,
  COUNT(*) FILTER (WHERE is_active)     AS active_users,
  COUNT(*) FILTER (WHERE NOT is_active) AS inactive_users
FROM public.users;
